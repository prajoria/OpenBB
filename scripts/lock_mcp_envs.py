"""Compile and check the dual-MCP dependency locks (#2245).

``scripts/start-dual-mcp.ps1`` installs each MCP server environment from a
committed, fully pinned lock instead of resolving transitive
dependencies at launch. Direct inputs live in ``scripts/mcp_locks/*.in``.

Usage::

    python scripts/lock_mcp_envs.py            # sync: keep pins, apply input changes
    python scripts/lock_mcp_envs.py --upgrade  # deliberate refresh to latest
    python scripts/lock_mcp_envs.py --check    # exit 1 if a lock is stale
"""

import argparse
import difflib
import json
import re
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK_DIR = ROOT / "scripts" / "mcp_locks"
MANIFEST = (
    ROOT
    / "openbb_platform"
    / "extensions"
    / "mcp_server"
    / "openbb_mcp_server"
    / "assets"
    / "runtime_profiles.json"
)
TIMESTAMP_FORMAT = "%Y-%m-%dT%H:%M:%SZ"
HEADER_PREFIXES = (
    "# Generated by scripts/lock_mcp_envs.py",
    "# Refresh:",
    "# locked-at:",
)
LOCKED_AT = re.compile(r"^# locked-at: (\S+)\s*$", re.MULTILINE)


@dataclass(frozen=True)
class LockSpec:
    """One MCP environment: its input file, lock file, and excluded editables."""

    name: str
    no_emit: tuple[str, ...] = ()

    @property
    def in_path(self) -> Path:
        """Return the direct-input file."""
        return LOCK_DIR / f"{self.name}.in"

    @property
    def out_path(self) -> Path:
        """Return the committed lock file."""
        return LOCK_DIR / f"{self.name}.txt"


ENVIRONMENTS = (
    LockSpec(
        "platform-mcp",
        no_emit=("openbb", "openbb-core", "openbb-platform-api", "openbb-mcp-server"),
    ),
    LockSpec("workspace-mcp"),
)

CompileFn = Callable[..., None]


def parse_locked_at(text: str) -> datetime:
    """Return the lock's compile timestamp."""
    match = LOCKED_AT.search(text)
    if match is None:
        raise ValueError("missing locked-at header")
    return datetime.strptime(match.group(1), TIMESTAMP_FORMAT).replace(tzinfo=UTC)


def lock_body(text: str) -> str:
    """Return the lock text without the generator header."""
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith(HEADER_PREFIXES):
        lines.pop(0)
    return "".join(lines)


def render(spec: LockSpec, body: str, locked_at: datetime) -> str:
    """Return a lock file: generator header followed by the compiled body."""
    return (
        f"# Generated by scripts/lock_mcp_envs.py from {spec.in_path.name}"
        " - do not edit.\n"
        "# Refresh: python scripts/lock_mcp_envs.py --upgrade\n"
        f"# locked-at: {locked_at.strftime(TIMESTAMP_FORMAT)}\n"
        f"{body}"
    )


def read_pins(text: str) -> dict[str, str]:
    """Return pinned versions keyed by PEP 503-normalized distribution name."""
    pins = {}
    for line in text.splitlines():
        if not line or line[0] in " #-" or "==" not in line:
            continue
        name, rest = line.split("==", 1)
        version = rest.split(";", 1)[0].split()[0]
        pins[re.sub(r"[-_.]+", "-", name.strip()).lower()] = version
    return pins


def compile_lock(spec: LockSpec, output: Path, *, upgrade: bool) -> None:
    """Compile ``spec`` into ``output``, preserving pins already in ``output``.

    Runs from LOCK_DIR with relative inputs so annotations stay
    machine-independent. Hashes are generated because the launcher installs
    each lock with ``uv pip sync --require-hashes`` (#2282).
    """
    command = [
        "uv",
        "pip",
        "compile",
        spec.in_path.name,
        "--universal",
        "--python-version",
        "3.13",
        "--no-header",
        "--generate-hashes",
        "--quiet",
        "--output-file",
        str(output),
    ]
    for name in spec.no_emit:
        command += ["--no-emit-package", name]
    if upgrade:
        command.append("--upgrade")
    # Fixed executable; arguments are passed without a shell.
    subprocess.run(command, cwd=LOCK_DIR, check=True)  # noqa: S603


def _recompile(spec: LockSpec, *, upgrade: bool, compile_fn: CompileFn) -> str:
    """Return a freshly compiled body seeded with the committed pins."""
    scratch = LOCK_DIR / f".{spec.name}.compile.txt"
    try:
        if spec.out_path.exists():
            scratch.write_text(
                lock_body(spec.out_path.read_text(encoding="utf-8")),
                encoding="utf-8",
            )
        compile_fn(spec, scratch, upgrade=upgrade)
        return scratch.read_text(encoding="utf-8")
    finally:
        scratch.unlink(missing_ok=True)


def sync(
    spec: LockSpec,
    *,
    upgrade: bool,
    compile_fn: CompileFn = compile_lock,
    now: datetime | None = None,
) -> bool:
    """Recompile ``spec``; write it with a new timestamp only if the body changed."""
    body = _recompile(spec, upgrade=upgrade, compile_fn=compile_fn)
    if spec.out_path.exists() and body == lock_body(
        spec.out_path.read_text(encoding="utf-8")
    ):
        return False
    stamp = now or datetime.now(UTC).replace(microsecond=0)
    spec.out_path.write_text(render(spec, body, stamp), encoding="utf-8")
    return True


def check(spec: LockSpec, *, compile_fn: CompileFn = compile_lock) -> list[str]:
    """Return a unified diff between the committed and recompiled lock."""
    if not spec.out_path.exists():
        return [f"{spec.name}: lock file missing; run python scripts/lock_mcp_envs.py"]
    committed = lock_body(spec.out_path.read_text(encoding="utf-8"))
    recompiled = _recompile(spec, upgrade=False, compile_fn=compile_fn)
    return list(
        difflib.unified_diff(
            committed.splitlines(),
            recompiled.splitlines(),
            fromfile=f"{spec.name} (committed)",
            tofile=f"{spec.name} (recompiled)",
            lineterm="",
        )
    )


def check_required_versions(manifest: Path, platform_lock_text: str) -> list[str]:
    """Return mismatches between isolated_uv required versions and the lock."""
    pins = read_pins(platform_lock_text)
    profiles = json.loads(manifest.read_text(encoding="utf-8"))["profiles"]
    messages = []
    for name, profile in profiles.items():
        if profile.get("installation", "isolated_uv") != "isolated_uv":
            continue
        for package, required in profile.get("required_versions", {}).items():
            locked = pins.get(package)
            if locked != required:
                messages.append(
                    f"{name}: runtime_profiles.json requires {package}=={required}"
                    f" but platform-mcp.txt pins {locked or 'nothing'}"
                )
    return messages


def main(argv: list[str] | None = None) -> int:
    """Sync, upgrade, or check every MCP environment lock."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--upgrade", action="store_true", help="refresh to latest")
    mode.add_argument("--check", action="store_true", help="fail on stale locks")
    args = parser.parse_args(argv)

    if args.check:
        problems = [line for spec in ENVIRONMENTS for line in check(spec)]
        platform = ENVIRONMENTS[0].out_path
        if platform.exists():
            problems += check_required_versions(
                MANIFEST, platform.read_text(encoding="utf-8")
            )
        for line in problems:
            sys.stdout.write(f"{line}\n")
        if problems:
            sys.stdout.write(
                "Dependency locks are stale; run python scripts/lock_mcp_envs.py\n"
            )
            return 1
        sys.stdout.write("Dependency locks are current.\n")
        return 0

    for spec in ENVIRONMENTS:
        written = sync(spec, upgrade=args.upgrade)
        state = "written" if written else "unchanged"
        sys.stdout.write(f"{spec.out_path.name}: {state}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
